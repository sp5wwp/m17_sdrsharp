#!/usr/bin/env python3
"""Generate plugin/src/Native/M17RxStructs.g.cs from layout_dump's output (explicit C offsets)."""
import re, sys
names = {"m17rx_link_t": "M17RxLink", "m17rx_status_t": "M17RxStatus", "m17rx_event_t": "M17RxEvent", "m17rx_config_t": "M17RxConfig"}
cs = {"int": "int", "uint": "uint", "ushort": "ushort", "float": "float", "double": "double", "link": "M17RxLink"}
def pascal(s): return "".join(p.capitalize() for p in s.split("_"))
sizes, fields = {}, {}
for line in open(sys.argv[1]):
    p = line.split()
    if p[0] == "size": sizes[p[1]] = int(p[2]); continue
    st, f, off, size, n, kind = p[0], p[1], int(p[2]), int(p[3]), int(p[4]), p[5]
    fields.setdefault(st, []).append((f, off, size, n, kind))
out = ["// <auto-generated> by tools/gen_interop.py from the C headers' real layout. Do not edit. </auto-generated>",
       "// SPDX-License-Identifier: GPL-2.0-or-later WITH AdditionRef-SDRSharp-exception",
       "using System.Runtime.InteropServices;", "", "namespace SDRSharp.M17.Native", "{"]
for c, cname in names.items():
    out.append(f"    [StructLayout(LayoutKind.Explicit, Size = {sizes[c]})]")
    out.append(f"    public unsafe struct {cname}")
    out.append("    {")
    out.append(f"        public const int NativeSize = {sizes[c]};")
    for f, off, size, n, kind in fields[c]:
        name = pascal(f)
        if kind in ("str", "bytes"):
            out.append(f"        [FieldOffset({off})] public fixed byte {name}[{n}];")
        elif kind == "floats":
            out.append(f"        [FieldOffset({off})] public fixed float {name}[{n}];")
        else:
            out.append(f"        [FieldOffset({off})] public {cs[kind]} {name};")
    out.append("    }")
    out.append("")
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
